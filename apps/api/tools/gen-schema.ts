// Writes Better Auth's SQL (D1 is SQLite) from the same config the Worker uses, so the tables never drift from the plugins.
// `pnpm --filter api schema` regenerates migrations/0002_better_auth.sql; run it whenever a plugin or option changes.
import { writeFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import { getMigrations } from 'better-auth/db/migration';
import { createAuth } from '../src/auth.ts';

const database = new DatabaseSync(':memory:');
database.exec('CREATE TABLE invite (email TEXT PRIMARY KEY, disabled INTEGER NOT NULL DEFAULT 0)');
const auth = createAuth(
    {
        PUBLIC_URL: 'http://localhost:5173',
        BETTER_AUTH_SECRET: 'x'.repeat(32),
        ADMIN_EMAILS: '',
        ACCESS_TOKEN_SECONDS: '900',
        GOOGLE_CLIENT_ID: 'x',
        GOOGLE_CLIENT_SECRET: 'x',
        GOOGLE_AUTHORIZE_URL: 'http://idp/authorize',
        GOOGLE_TOKEN_URL: 'http://idp/token',
        GOOGLE_USERINFO_URL: 'http://idp/userinfo',
        GITHUB_CLIENT_ID: 'x',
        GITHUB_CLIENT_SECRET: 'x',
        GITHUB_AUTHORIZE_URL: 'http://idp/authorize',
        GITHUB_TOKEN_URL: 'http://idp/token',
        GITHUB_USER_URL: 'http://idp/user',
        GITHUB_EMAILS_URL: 'http://idp/emails',
    },
    database as never,
);
const { compileMigrations } = await getMigrations(auth.options);
const sql = await compileMigrations();
writeFileSync(
    process.argv[2] ?? 'better-auth.sql',
    `-- Generated by tools/gen-schema.ts (pnpm --filter api schema); do not edit.\n${sql}\n`,
);
console.log(`${sql.split('\n').length} lines`);
